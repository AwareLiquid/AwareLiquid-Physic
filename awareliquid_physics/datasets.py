"""
datasets.py — trajectory datasets generated by the zero-parameter physics
engine (physics_ops). v0.2 (M3) adds the FIELD family: a 1D periodic string
(wave equation, discretised) whose true trajectories come from the same
velocity-Verlet integrator the learned models are benchmarked against.

Uniform data contract: qs, ps are (n_traj, steps + 1, N, dim) with the same
dt used by the model, so a trajectory is a phase-space path the Hamiltonian
head can be trained on directly.

The string is PERIODIC on purpose: the FNO spectral layer of
OperatorPotential assumes a periodic domain, so the ground truth and the
inductive bias agree (a physical, not cosmetic, choice).
"""

from __future__ import annotations

import math
from typing import Tuple

import torch

from .physics_ops import (integrate_verlet, pairwise_gravity,
                          reflect_in_box, resolve_sphere_collisions)


def gen_wave_1d(n_traj: int, steps: int, dt: float, N: int, c: float,
                generator: torch.Generator, n_modes: int = 5,
                device: str = "cpu") -> Tuple[torch.Tensor, torch.Tensor]:
    """A family of 1D periodic strings (linear wave equation, discretised).

    Hamiltonian:  H = sum_i [ p_i^2/2 + c^2/2 (q_{i+1} - q_i)^2 ]   (cyclic)

    so the acceleration is the discrete Laplacian
        a_i = c^2 (q_{i+1} + q_{i-1} - 2 q_i).

    Each trajectory starts from a SMOOTH random perturbation (a few low
    Fourier modes) and is integrated with velocity-Verlet (symplectic,
    O(dt^2) bounded energy error) — the ground-truth engine the learned
    models are scored against: compute, don't memorise.

    Returns (qs, ps), each (n_traj, steps + 1, N, 1) on `device`.
    """
    qs, ps = [], []
    for b in range(n_traj):
        q0 = _smooth_field(n_traj, N, generator, n_modes, device)[b:b + 1]  # (1, N)
        p0 = torch.randn(1, N, generator=generator, device=device) * 0.3

        q = q0.unsqueeze(-1)   # (1, N, 1)
        p = p0.unsqueeze(-1)

        def accel(pos: torch.Tensor) -> torch.Tensor:
            ql = torch.roll(pos, 1, dims=1)
            qr = torch.roll(pos, -1, dims=1)
            return (c * c) * (ql + qr - 2.0 * pos)

        q_list, p_list = [q], [p]
        a = accel(q)
        for _ in range(steps):
            q, p, a = integrate_verlet(q, p, accel, dt, accel=a)
            q_list.append(q)
            p_list.append(p)
        qs.append(torch.stack(q_list))   # (steps+1, 1, N, 1)
        ps.append(torch.stack(p_list))
    return torch.cat(qs, dim=1).permute(1, 0, 2, 3), \
           torch.cat(ps, dim=1).permute(1, 0, 2, 3)   # (n_traj, steps+1, N, 1)


def gen_wave_1d_inhomogeneous(n_traj: int, steps: int, dt: float, N: int,
                               c_mean: float, c_var: float,
                               generator: torch.Generator, n_modes: int = 4,
                               device: str = "cpu"
                               ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """A family of 1D INHOMOGENEOUS periodic strings: the wave speed is a
    smooth random FIELD c(x) drawn per trajectory (a few low Fourier modes
    around c_mean), not a global constant.

    Hamiltonian:  H = sum_i [ p_i^2/2 + c_i^2/2 (q_{i+1} - q_i)^2 ]   (cyclic)

    so the acceleration is the VARIABLE-COEFFICIENT discrete Laplacian
        a_i = c_i^2 (q_{i+1} - q_i) - c_{i-1}^2 (q_i - q_{i-1}).

    This is the hard version of gen_wave_1d: the hidden parameter is the whole
    SPATIAL FIELD c(x), which a static potential can only approximate by an
    average medium — real per-trajectory adaptation (liquid system-ID) is what
    buys accuracy. Ground truth via velocity-Verlet as before.

    Returns (qs, ps, cs): qs/ps (n_traj, steps+1, N, 1), cs (n_traj, N) the
    per-trajectory wave-speed fields (for the energy diagnostic), on `device`.
    """
    qs, ps, cfields = [], [], []
    for _ in range(n_traj):
        c = c_mean + c_var * _smooth_field(1, N, generator, n_modes, device)  # (1, N)
        c = c.clamp_min(0.2 * c_mean)
        q0 = _smooth_field(1, N, generator, 5, device)                        # (1, N)
        p0 = torch.randn(1, N, generator=generator, device=device) * 0.3

        q = q0.unsqueeze(-1)   # (1, N, 1)
        p = p0.unsqueeze(-1)
        c2 = (c * c).unsqueeze(-1)                # (1, N, 1)
        c2_shift = torch.roll(c2, 1, dims=1)

        def accel(pos: torch.Tensor) -> torch.Tensor:
            dq_f = torch.roll(pos, -1, dims=1) - pos   # q_{i+1} - q_i
            dq_b = pos - torch.roll(pos, 1, dims=1)    # q_i - q_{i-1}
            return c2 * dq_f - c2_shift * dq_b

        q_list, p_list = [q], [p]
        a = accel(q)
        for _ in range(steps):
            q, p, a = integrate_verlet(q, p, accel, dt, accel=a)
            q_list.append(q)
            p_list.append(p)
        qs.append(torch.stack(q_list))
        ps.append(torch.stack(p_list))
        cfields.append(c)
    return (torch.cat(qs, dim=1).permute(1, 0, 2, 3),
            torch.cat(ps, dim=1).permute(1, 0, 2, 3),
            torch.cat(cfields, dim=0))


def gen_nbody(n_traj: int, steps: int, dt: float, N: int, D: int,
              mass_lo: float = 0.5, mass_hi: float = 1.5, G: float = 1.0,
              softening: float = 0.05, box: float = 2.0, radius: float = 0.1,
              restitution: float = 0.9, generator: torch.Generator = None,
              device: str = "cpu"
              ) -> Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Gravitational N-body systems with SOFT collisions, in a reflecting box.

    Hidden parameter: the per-particle MASS field m_i ~ U[mass_lo, mass_hi]
    (each trajectory has a different mass distribution). Dynamics:
      * acceleration = pairwise_gravity (softened, momentum-conserving);
      * velocity-Verlet integration (symplectic);
      * sphere-sphere impulse collisions (momentum-conserving);
      * reflection off the box walls [-box, box]^D.

    This is the irregular-node system for P2-1: no grid, so the FNO spectral
    potential does not apply; the correct energy structure is a PAIR potential
    (see PairwisePotential). Ground truth via the zero-parameter physics_ops
    engine — compute, don't memorise.

    Returns (qs, ps, mass): qs/ps (n_traj, steps+1, N, D) positions/velocities,
    mass (n_traj, N). On `device`.
    """
    if generator is None:
        generator = torch.Generator(device=device)
    qs, ps, masses = [], [], []
    for _ in range(n_traj):
        mass = mass_lo + (mass_hi - mass_lo) * torch.rand(
            N, generator=generator, device=device)                 # (N,)

        # Initial state: non-overlapping positions in the box, small velocities.
        pos = torch.rand(N, D, generator=generator, device=device) * (2 * box) - box
        vel = torch.randn(N, D, generator=generator, device=device) * 0.2
        pos, vel = reflect_in_box(pos, vel, -box, box)

        def accel_fn(p):
            return pairwise_gravity(p, mass, G=G, softening=softening)

        p_list, v_list = [pos], [vel]
        a = accel_fn(pos)
        for _ in range(steps):
            pos, vel, a = integrate_verlet(pos, vel, accel_fn, dt, accel=a)
            vel = resolve_sphere_collisions(pos, vel, radius=radius,
                                            mass=mass, restitution=restitution)
            pos, vel = reflect_in_box(pos, vel, -box, box)
            p_list.append(pos)
            v_list.append(vel)
        qs.append(torch.stack(p_list))
        ps.append(torch.stack(v_list))
        masses.append(mass)
    return (torch.stack(qs), torch.stack(ps), torch.stack(masses))


def _smooth_field(n_traj: int, N: int, generator: torch.Generator,
                  n_modes: int, device: str = "cpu") -> torch.Tensor:
    """Random smooth field: a few low Fourier modes with random amplitudes and
    phases. Returns (n_traj, N) on `device`."""
    x = torch.arange(N, dtype=torch.float32, device=device)
    field = torch.zeros(n_traj, N, device=device)
    for m in range(1, n_modes + 1):
        amp = torch.rand(n_traj, generator=generator, device=device) * (0.5 / m)
        phase = torch.rand(n_traj, generator=generator, device=device) * 2.0 * math.pi
        field += amp.unsqueeze(-1) * torch.sin(
            2.0 * math.pi * m * x / N + phase.unsqueeze(-1))
    return field


def gen_wave_2d(n_traj: int, steps: int, dt: float, H: int, W: int, c: float,
                generator: torch.Generator, n_modes: int = 3,
                device: str = "cpu") -> Tuple[torch.Tensor, torch.Tensor]:
    """A family of 2D periodic membranes (linear wave equation on a torus).

    Hamiltonian:  H = sum_{x,y} [ p^2/2 + c^2/2 ((q_{x+1,y}-q)^2 + (q_{x,y+1}-q)^2) ]

    so the acceleration is the 2D discrete Laplacian (cyclic):
        a = c^2 (q_{x+1,y} + q_{x-1,y} + q_{x,y+1} + q_{x,y-1} - 4 q).

    Each trajectory starts from a SMOOTH random 2D perturbation (a few low
    Fourier modes) and is integrated with velocity-Verlet — the ground-truth
    engine. Periodic on purpose: the SpectralConv2d potential assumes a
    periodic domain, so truth and inductive bias agree.

    Returns (qs, ps), each (n_traj, steps + 1, H, W, 1) on `device`.
    """
    qs, ps = [], []
    for _ in range(n_traj):
        q0 = _smooth_field_2d(1, H, W, generator, n_modes, device)  # (1, H, W)
        p0 = torch.randn(1, H, W, generator=generator, device=device) * 0.3

        q = q0.unsqueeze(-1)   # (1, H, W, 1)
        p = p0.unsqueeze(-1)
        c2 = c * c

        def accel(pos: torch.Tensor) -> torch.Tensor:
            lap = (torch.roll(pos, 1, dims=1) + torch.roll(pos, -1, dims=1)
                   + torch.roll(pos, 1, dims=2) + torch.roll(pos, -1, dims=2)
                   - 4.0 * pos)
            return c2 * lap

        q_list, p_list = [q], [p]
        a = accel(q)
        for _ in range(steps):
            q, p, a = integrate_verlet(q, p, accel, dt, accel=a)
            q_list.append(q)
            p_list.append(p)
        qs.append(torch.stack(q_list))
        ps.append(torch.stack(p_list))
    return (torch.cat(qs, dim=1).permute(1, 0, 2, 3, 4),
            torch.cat(ps, dim=1).permute(1, 0, 2, 3, 4))


def _smooth_field_2d(n_traj: int, H: int, W: int, generator: torch.Generator,
                     n_modes: int, device: str = "cpu") -> torch.Tensor:
    """Random smooth 2D field: low Fourier modes on a H x W torus. Returns
    (n_traj, H, W)."""
    xs = torch.arange(H, dtype=torch.float32, device=device)
    ys = torch.arange(W, dtype=torch.float32, device=device)
    field = torch.zeros(n_traj, H, W, device=device)
    for mx in range(1, n_modes + 1):
        for my in range(1, n_modes + 1):
            amp = torch.rand(n_traj, generator=generator, device=device) / (mx * my)
            phase = torch.rand(n_traj, generator=generator, device=device) * 2.0 * math.pi
            wave = torch.sin(2.0 * math.pi * mx * xs[:, None] / H
                             + 2.0 * math.pi * my * ys[None, :] / W)
            field += amp[:, None, None] * (wave[None] + phase[:, None, None])
    return field
