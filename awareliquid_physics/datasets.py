"""
datasets.py — trajectory datasets generated by the zero-parameter physics
engine (physics_ops). v0.2 (M3) adds the FIELD family: a 1D periodic string
(wave equation, discretised) whose true trajectories come from the same
velocity-Verlet integrator the learned models are benchmarked against.

Uniform data contract: qs, ps are (n_traj, steps + 1, N, dim) with the same
dt used by the model, so a trajectory is a phase-space path the Hamiltonian
head can be trained on directly.

The string is PERIODIC on purpose: the FNO spectral layer of
OperatorPotential assumes a periodic domain, so the ground truth and the
inductive bias agree (a physical, not cosmetic, choice).
"""

from __future__ import annotations

import math
from typing import Tuple

import torch

from .physics_ops import integrate_verlet


def gen_wave_1d(n_traj: int, steps: int, dt: float, N: int, c: float,
                generator: torch.Generator, n_modes: int = 5
                ) -> Tuple[torch.Tensor, torch.Tensor]:
    """A family of 1D periodic strings (linear wave equation, discretised).

    Hamiltonian:  H = sum_i [ p_i^2/2 + c^2/2 (q_{i+1} - q_i)^2 ]   (cyclic)

    so the acceleration is the discrete Laplacian
        a_i = c^2 (q_{i+1} + q_{i-1} - 2 q_i).

    Each trajectory starts from a SMOOTH random perturbation (a few low
    Fourier modes) and is integrated with velocity-Verlet (symplectic,
    O(dt^2) bounded energy error) — the ground-truth engine the learned
    models are scored against: compute, don't memorise.

    Returns (qs, ps), each (n_traj, steps + 1, N, 1).
    """
    qs, ps = [], []
    for b in range(n_traj):
        q0 = _smooth_field(n_traj, N, generator, n_modes)[b:b + 1]  # (1, N)
        p0 = torch.randn(1, N, generator=generator) * 0.3

        q = q0.unsqueeze(-1)   # (1, N, 1)
        p = p0.unsqueeze(-1)

        def accel(pos: torch.Tensor) -> torch.Tensor:
            ql = torch.roll(pos, 1, dims=1)
            qr = torch.roll(pos, -1, dims=1)
            return (c * c) * (ql + qr - 2.0 * pos)

        q_list, p_list = [q], [p]
        a = accel(q)
        for _ in range(steps):
            q, p, a = integrate_verlet(q, p, accel, dt, accel=a)
            q_list.append(q)
            p_list.append(p)
        qs.append(torch.stack(q_list))   # (steps+1, 1, N, 1)
        ps.append(torch.stack(p_list))
    return torch.cat(qs, dim=1).permute(1, 0, 2, 3), \
           torch.cat(ps, dim=1).permute(1, 0, 2, 3)   # (n_traj, steps+1, N, 1)


def _smooth_field(n_traj: int, N: int, generator: torch.Generator,
                  n_modes: int) -> torch.Tensor:
    """Random smooth field: a few low Fourier modes with random amplitudes and
    phases. Returns (n_traj, N)."""
    x = torch.arange(N, dtype=torch.float32)
    field = torch.zeros(n_traj, N)
    for m in range(1, n_modes + 1):
        amp = torch.rand(n_traj, generator=generator) * (0.5 / m)
        phase = torch.rand(n_traj, generator=generator) * 2.0 * math.pi
        field += amp.unsqueeze(-1) * torch.sin(
            2.0 * math.pi * m * x / N + phase.unsqueeze(-1))
    return field
